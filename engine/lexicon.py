"""Shopper-language knowledge base for the rule planner, grounded in the catalog.

Every table is a plain literal. Conventions:

* Keys are lowercase and already in the canonical token form of
  ``engine.text.raw_tokens``: words of [a-z0-9] separated by single spaces,
  compounds joined ("tshirt", "flipflop", "sweatshirt", "handbag", "earring",
  "waterbottle", "raincoat", "offwhite", "plussize", "pyjama", "swimsuit",
  "jumpsuit", "bodysuit", "backpack", "sunglasses", "nightgown", "heel",
  "hoodie", "vneck", "highwaist", "offshoulder", "crossbody", "overall").
  Give singular keys; irregular plurals (ladies, scarves, babies...) are listed.
* Product types, colours, patterns, sections and audiences are exact catalog
  strings. Keywords are words that catalog names or descriptions actually use
  ("imitation leather", not "faux leather"; "trainers" as well as "sneakers").
* Verified against data/products.json (see tests/test_lexicon.py).

The matcher (engine/vocab.py) stems every key and query token and takes the
longest phrase first, so a multi-word key shields its words ("baby blue" is a
colour, not a baby; "dog food" is not sold although "dog" is a type). A key
that appears in two tables gives one span both meanings ("baby clothes" is an
audience and a garment group). OCCASIONS values are shared dicts: read only.

Catalog quirks this encodes: British English (trainers, jumper, trousers,
dressing gown); jeans are type Trousers described as "jeans"; there is no navy
or brown colour (Dark Blue, Yellowish Brown); maternity is section "Mama" and
plus size is "H&M+"; "office"/"formal"/"evening" never appear, so smart and
party wear is reached through sections and fabric words (tailored, satin,
sequins); phone cases, headphones, USB cables and laptop sleeves are
"Other accessories"; "Side table" products are laundry detergent.
"""

